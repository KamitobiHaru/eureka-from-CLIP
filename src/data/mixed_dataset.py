"""Dataset for loading precomputed mixed pseudo-video sequences from disk.

The sequences are generated by ``scripts/precompute_motion_sequences.py`` and
stored as ``.npy`` (frame embeddings) + ``.json`` (caption metadata) pairs.

Output format matches ``SequenceDataset`` so that ``sequence_collate_fn``
(variable-length padding + BERT tokenization) works unchanged.
"""

import json
from pathlib import Path
from typing import List, Optional, Tuple

import numpy as np
import torch
from torch.utils.data import Dataset, DataLoader
from transformers import BertTokenizer


class MixedSequenceDataset(Dataset):
    """Load precomputed mixed sequences (motion + connector) from disk.

    Each sample yields:
        frame_embs:       [K, 512] float32 torch.Tensor
        positions:        [K, 3]   float32 (cx, cy, scale) normalised to [0,1],
                                   or all zeros for connector sequences
        correct_caption:  str (temporally ordered, e.g. "First, a dog. Then, a cat.")
    """

    def __init__(self, cache_dir: str, split: str = "train2017"):
        self.cache_dir = Path(cache_dir) / split
        samples_path = self.cache_dir / "samples.json"

        if not samples_path.exists():
            raise FileNotFoundError(
                f"No precomputed sequences found at {samples_path}. "
                f"Run scripts/precompute_motion_sequences.py first."
            )

        with open(samples_path) as f:
            self.samples: List[dict] = json.load(f)

    def __len__(self) -> int:
        return len(self.samples)

    def __getitem__(self, idx: int) -> Tuple[torch.Tensor, torch.Tensor, str]:
        info = self.samples[idx]
        sid = info["id"]

        embs = np.load(self.cache_dir / f"seq_{sid:06d}.npy").astype(np.float32)
        with open(self.cache_dir / f"seq_{sid:06d}.json") as f:
            meta = json.load(f)

        K = embs.shape[0]
        if "positions" in meta:
            pos = np.array(meta["positions"], dtype=np.float32)  # [K, 3]
        else:
            pos = np.zeros((K, 3), dtype=np.float32)             # connector placeholder

        return (
            torch.from_numpy(embs),   # [K, 512]
            torch.from_numpy(pos),    # [K, 3]
            meta["correct_caption"],
        )


def get_mixed_dataloader(
    cache_dir: str,
    split: str,
    tokenizer: BertTokenizer,
    batch_size: int = 32,
    shuffle: bool = True,
    num_workers: int = 4,
    max_text_len: int = 77,
    generator: Optional[torch.Generator] = None,
) -> DataLoader:
    """Convenience factory returning a DataLoader over the mixed dataset.

    Uses the same ``sequence_collate_fn`` from ``src.data`` for variable-length
    frame padding and BERT tokenization.
    """
    from .sequence_dataset import sequence_collate_fn

    dataset = MixedSequenceDataset(cache_dir=cache_dir, split=split)
    return DataLoader(
        dataset,
        batch_size=batch_size,
        shuffle=shuffle,
        num_workers=num_workers,
        collate_fn=sequence_collate_fn(tokenizer, max_text_len=max_text_len),
        pin_memory=True,
        generator=generator,
    )
